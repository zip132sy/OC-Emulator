  let currentLang = localStorage.getItem(STORAGE_KEY) || '';

  function getLang() {
    return currentLang || 'zh';
  }

  function setLang(lang) {
    if (!translations[lang]) lang = 'zh';
    currentLang = lang;
    localStorage.setItem(STORAGE_KEY, lang);
  }

  function t(key, vars) {
    const dict = translations[currentLang] || translations.zh;
    let s = dict[key] != null ? dict[key] : (translations.zh[key] || key);
    if (vars) {
      s = String(s).replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? vars[k] : m));
    }
    return s;
  }

  function isFirstTime() {
    return !localStorage.getItem(STORAGE_KEY);
  }

  return { getLang, setLang, t, isFirstTime, translations };
